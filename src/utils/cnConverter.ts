const TRAD_TO_SIMP_MAP = new Map<string, string>();
const SIMP_TO_TRAD_MAP = new Map<string, string>();

PAIRS.forEach(([trad, simp]) => {
    TRAD_TO_SIMP_MAP.set(trad, simp);
    if (!SIMP_TO_TRAD_MAP.has(simp)) {
        SIMP_TO_TRAD_MAP.set(simp, trad);
    }
});

/**
 * 转换为简体中文
 */
export function toSimplified(text: string): string {
    if (!text) return "";
    let result = "";
    for (const char of text) {
        result += TRAD_TO_SIMP_MAP.get(char) || char;
    }
    return result;
}

/**
 * 转换为繁体中文
 */
export function toTraditional(text: string): string {
    if (!text) return "";
    let result = "";
    for (const char of text) {
        result += SIMP_TO_TRAD_MAP.get(char) || char;
    }
    return result;
}

/**
 * 简繁体通配/混合文本匹配
 * 只要目标文本与搜索文本在简体、繁体或原始字符串中的任何一种形态下匹配，即返回 true
 */
export function matchChineseText(target: string, search: string): boolean {
    if (!search || !search.trim()) return true;
    if (!target) return false;

    const targetLower = target.toLowerCase();
    const searchLower = search.trim().toLowerCase();

    // 1. 原始匹配
    if (targetLower.includes(searchLower)) return true;

    // 2. 统一转换为简体匹配
    const targetSimp = toSimplified(targetLower);
    const searchSimp = toSimplified(searchLower);
    if (targetSimp.includes(searchSimp)) return true;

    // 3. 统一转换为繁体匹配
    const targetTrad = toTraditional(targetLower);
    const searchTrad = toTraditional(searchLower);
    if (targetTrad.includes(searchTrad)) return true;

    return false;
}
